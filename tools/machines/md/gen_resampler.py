#!/usr/bin/env python3
"""Polyphase FIR for 44.1 -> 48 kHz (L = 160, M = 147) used by the TRX-B2 bridge.

Kaiser-windowed sinc, 24 taps per phase, -6 dB at 24 kHz, coefficients in Q14 (the centre taps
of some phases exceed 1.0). Flat to 20 kHz; every image that
would fold back below 20 kHz (above 28 kHz before decimation) is at least ~65 dB down. Each
phase is quantised to Q14 and renormalised to sum exactly 16384, so DC (the TICK pulse) passes
with gain 1 at every phase.

usage: gen_resampler.py out.h
"""
import math
import sys

L, M, T = 160, 147, 24
SHIFT = 14
ONE = 1 << SHIFT
FS_IN = 44100.0
CUTOFF = 24000.0
BETA = 6.2


def i0(x):
    s, term, k = 1.0, 1.0, 1
    while term > 1e-12 * s:
        term *= (x / (2 * k)) ** 2
        s += term
        k += 1
    return s


def design():
    n_taps = L * T
    fc = CUTOFF / (FS_IN * L)                     # cycles per prototype sample
    mid = (n_taps - 1) / 2
    h = []
    for n in range(n_taps):
        t = n - mid
        sinc = 2 * fc if t == 0 else math.sin(2 * math.pi * fc * t) / (math.pi * t)
        w = i0(BETA * math.sqrt(1 - (2 * t / (n_taps - 1)) ** 2)) / i0(BETA)
        h.append(sinc * w * L)
    phases = []
    for p in range(L):
        c = [h[p + L * k] for k in range(T)]
        q = [round(x * ONE) for x in c]
        # renormalise: push the rounding error into the largest tap
        err = ONE - sum(q)
        q[max(range(T), key=lambda k: abs(c[k]))] += err
        phases.append(q)
    # le pont accumule (x >> 8) * c sur 32 bits : |x >> 8| <= 2^15
    worst = max(sum(abs(c) for c in q) for q in phases)
    assert (1 << 15) * worst < (1 << 31), worst
    assert max(abs(c) for q in phases for c in q) < (1 << 15)
    return phases


def response(phases, f):
    """Magnitude of the prototype at frequency f (Hz, at the 44.1 kHz input rate)."""
    re = im = 0.0
    for p, q in enumerate(phases):
        for k, c in enumerate(q):
            n = p + L * k
            w = 2 * math.pi * f / (FS_IN * L) * n
            re += c * math.cos(w)
            im -= c * math.sin(w)
    return math.hypot(re, im) / (ONE * L)


if __name__ == '__main__':
    ph = design()
    for f in (1000, 10000, 16000, 20000, 22050, 24000, 28000, 32000, 40000):
        print('%6d Hz %7.2f dB' % (f, 20 * math.log10(max(response(ph, f), 1e-12))), file=sys.stderr)
    with open(sys.argv[1], 'w') as out:
        out.write('/* Generated by gen_resampler.py: 44.1 -> 48 kHz, L=%d M=%d, %d taps per phase, Q%d. */\n' % (L, M, T, SHIFT))
        out.write('#define RS_L %d\n#define RS_M %d\n#define RS_T %d\n#define RS_SHIFT %d\n' % (L, M, T, SHIFT))
        out.write('static const short rs_coef[RS_L][RS_T] = {\n')
        for q in ph:
            out.write('\t{ %s },\n' % ', '.join(str(x) for x in q))
        out.write('};\n')
